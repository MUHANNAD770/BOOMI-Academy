/* tamarbuta.js — نطق التاء المربوطة (ة) حسب موضعها في الجملة. للمحرك فقط: النص المعروض لا يتغيّر.
   • الوقف (آخر الجملة أو قبل علامة ترقيم): هاء ساكنة ← نكتب للمحرك «ةْ» (بلا سكون قد يُسقط المحرك الهاء).
   • الوصل (بعدها كلمة): تاء بحركتها الإعرابية. الحركة المكتوبة في النص تبقى كما هي. وإن لم تُكتب:
     (١) جمل الموقع الثابتة: الحركة من خريطة أعدّتها أداة التشكيل CATT (voices/tm-map.json، tools/tamarbuta/)
     (٢) نص جديد (ردود بومي…): قواعد نحوية: بعد حرف الجر كسرة، بعد «إنّ وأخواتها» أو فعل متعدٍّ فتحة،
         الصفة تتبع موصوفها (اللُّغَةُ الْعَرَبِيَّةُ، شَجَرَةٌ كَبِيرَةٌ)، وإلا ضمة (مبتدأ/فاعل/خبر/عنوان).
   يعمل في المتصفح (window.TaMarbuta) وفي Node (require): مصدر واحد للصوتين وخادم النطق والصوت المستنسخ وتوليد المقاطع. */
(function(root){
 'use strict';
 const TA='ة',SUK='ْ',FAT='َ',DAM='ُ',KAS='ِ',TANW={'َ':'ً','ُ':'ٌ','ِ':'ٍ'};
 const H=/[ً-ْٰ]/g,AR=/[ء-ي]/,PU='«»"\'()\\[\\].!؟?،,:;؛…',PUR=new RegExp('['+PU+']*$');
 const bare=w=>w.replace(H,'').replace(/[«»"'()\[\].!؟?،,:;؛…]/g,'');
 const PREP=new Set(['في','من','الى','إلى','على','عن','مع','عند','بعد','قبل','فوق','تحت','امام','أمام','خلف','بين','حول','دون','مثل','لدى','حتى','نحو','منذ','خلال','داخل','خارج','بجانب','عبر','ضد','وفي','ومن','وإلى','وعلى','وعن','ومع','وبين','وعند','فيها','بدون']);
 const NASB=new Set(['إن','ان','أن','لكن','ليت','لعل','كأن','ولكن','وإن','وأن']);
 /* أفعال متعدية شائعة (بعدها مفعول به منصوب) */
 const VT=new Set(['اقرأ','اقرئي','اكتب','اكتبي','اختر','اختاري','رتب','رتبي','انطق','انطقي','أكمل','أكملي','لاحظ','لاحظي','احفظ','احفظي','ارسم','ارسمي','املأ','املئي','استخدم','استخدمي','ردد','رددي','أعد','أعيدي','كرر','كرري','حدد','حددي','اذكر','اذكري','تعلم','تعلمي','صحح','صححي','لون','لوني','اسمع','اسمعي','شاهد','شاهدي','اكتشف','اكتشفي','رأيت','رأى','أحب','نحب','يحب','تحب','أرى','نرى','يرى','ترى','قرأ','قرأت','كتب','كتبت','أكل','أكلت','شرب','شربت','وجد','وجدت','اشترى','اشتريت','أخذ','أخذت','فتح','فتحت','حمل','حملت']);
 /* صفات مؤنثة شائعة: بعد نكرة منتهية بتاء مربوطة تكون نعتًا (لا إضافة) */
 const ADJ=new Set(['كبيرة','صغيرة','جميلة','جديدة','قديمة','طويلة','قصيرة','سعيدة','حزينة','لذيذة','سهلة','صعبة','واسعة','ضيقة','نظيفة','مفيدة','ملونة','كثيرة','قليلة','قوية','ضعيفة','سريعة','بطيئة','عالية','واضحة','صحيحة','خاطئة','ساكنة','مفتوحة','مربوطة','مشكولة','مختلفة','مناسبة','قصيرة','بسيطة','رائعة','ممتعة','مهمة','لطيفة','ذكية','نشيطة','هادئة','باردة','حارة','دافئة','خضراء','حمراء','زرقاء','صفراء','بيضاء','سوداء','ثانية','أولى','أخرى','كاملة','جيدة','عظيمة','غريبة','عادية','خاصة','عامة','كاملة','حلوة','ناضجة','طازجة','مضيئة','ملونة']);
 const isAdj=w=>{const b=bare(w);return ADJ.has(b)||/ية$/.test(b)};
 const hasAl=w=>/^(?:[وف])?(?:[بلك])?ال|^(?:[وف])?لل/.test(bare(w));
 const prepAttached=w=>/^(?:[وف])?(?:بال|كال|لل)/.test(bare(w));
 const endsBareTa=w=>new RegExp(TA+'['+PU+']*$').test(w);
 const taVowel=w=>{const m=w.match(new RegExp(TA+'([\\u064B-\\u0652])'));return m?m[1]:null};
 /* الحركة الإعرابية لتاء مربوطة غير مشكولة في الوصل */
 function guess(ws,i,done){const w=ws[i],p=i>0?ws[i-1]:'',pb=bare(p),n=ws[i+1]||'';
  /* نعت يتبع منعوته (الكلمة السابقة منتهية بتاء مربوطة) */
  if(p&&new RegExp(TA+'[\\u064B-\\u0652]?['+PU+']*$').test(p)&&hasAl(w)===hasAl(p)&&isAdj(w)){const v=done[i-1]||taVowel(p);if(v&&v!==SUK)return v}
  let v=DAM;
  if(prepAttached(w)||(p&&PREP.has(pb)))v=KAS;else if(p&&(NASB.has(pb)||VT.has(pb)))v=FAT;
  /* نكرة يتبعها نعت نكرة: تنوين (شَجَرَةٌ كَبِيرَةٌ، رِسَالَةً قَصِيرَةً) */
  if(!hasAl(w)&&n&&!hasAl(n)&&isAdj(n))v=TANW[v];
  return v}
 /* مفاتيح الخريطة بصيغة موحّدة (NFC): ترتيب الحركات قد يختلف بين النص والخريطة (الشدة مع الكسرة مثلًا) */
 const NK=s=>String(s).replace(/\s+/g,' ').trim().normalize('NFC'),NM=new WeakMap();
 const look=(map,s)=>{let m=NM.get(map);if(!m){m=new Map();for(const k in map)m.set(NK(k),map[k]);NM.set(map,m)}return m.get(NK(s))};
 function engine(t,map){if(!t||t.indexOf(TA)<0)return t;const s=String(t);
  let x=s;if(map){const v=look(map,s);if(v)x=v} /* حركات الوصل من أداة التشكيل، ثم الوقف والباقي بالقواعد */
  const ws=x.split(/(\s+)/),words=[],idx=[];ws.forEach((y,j)=>{if(y&&!/^\s+$/.test(y)){idx.push(j);words.push(y)}});
  const done={};
  for(let i=0;i<words.length;i++){const w=words[i];if(bare(w)==='ة')continue; /* حرف «ة» مذكورًا باسمه */
   if(!endsBareTa(w)){const v=taVowel(w);if(v)done[i]=v;continue}
   const tail=w.slice(w.lastIndexOf(TA)+1),next=words[i+1];
   const stop=/[.!؟?،,:;؛…]/.test(tail)||!next||!AR.test(next)||/^[.!؟?،,:;؛…\-—]/.test(next);
   const v=stop?SUK:guess(words,i,done);done[i]=v;
   const k=w.lastIndexOf(TA);words[i]=w.slice(0,k+1)+v+w.slice(k+1)}
  idx.forEach((j,n)=>ws[j]=words[n]);return ws.join('')}
 const api={engine,guess};
 if(typeof module!=='undefined'&&module.exports)module.exports=api;else root.TaMarbuta=api;
})(typeof window!=='undefined'?window:globalThis);
