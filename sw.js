/* تثبيت: الملفات الأساسية أولًا، ثم كل ملفات الموقع (الصور والأيقونات والبيانات والكود) ليعمل كل شيء بلا إنترنت.
   الصور الموجودة في نسخة سابقة تُنسخ منها بدل تنزيلها من جديد؛ الكود والبيانات تُجلب دائمًا جديدة. */
self.addEventListener('install', event => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    await Promise.allSettled(PRECACHE.map(url => cache.add(new Request(url, { cache: 'reload' }))));
    self.skipWaiting();
    const fresh = /\.(?:js|css|json|webmanifest|html?)$|\/$/i;
    const list = OFFLINE.filter(u => !PRECACHE.includes(u));
    let i = 0;
    const worker = async () => {
      while (i < list.length) {
        const u = list[i++];
        try {
          if (await cache.match(u)) continue;
          if (!fresh.test(u)) { const old = await caches.match(u, { ignoreSearch: true }); if (old) { await cache.put(u, old); continue; } }
          const r = await fetch(new Request(u, { cache: fresh.test(u) ? 'reload' : 'default' }));
          if (r && r.ok) await cache.put(u, r);
        } catch (_) {}
      }
    };
    await Promise.all(Array.from({ length: 6 }, worker));
    /* خط الموقع: نحفظه من أول زيارة (قبل أن يتحكّم عامل الخدمة في الصفحة) */
    try {
      const fc = await caches.open(FONTS);
      if (!(await fc.match(FONT_CSS))) {
        const css = await fetch(FONT_CSS);
        if (css.ok) {
          const txt = await css.clone().text();
          await fc.put(FONT_CSS, css);
          const urls = [...txt.matchAll(/url\((https:\/\/fonts\.gstatic\.com\/[^)]+)\)/g)].map(m => m[1]);
          await Promise.allSettled(urls.map(async u => { const r = await fetch(u); if (r.ok) await fc.put(u, r); }));
        }
      }
    } catch (_) {}
  })());
});

self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    const keys = await caches.keys();
    /* نحذف نسخ الموقع القديمة فقط؛ ذاكرات الأصوات (المقاطع المسجّلة، Gemini، صوتي الشخصي) تبقى */
    await Promise.all(keys.filter(k => k !== CACHE && /^hurufi-app-/.test(k)).map(k => caches.delete(k)));
    await self.clients.claim();
  })());
});

self.addEventListener('fetch', event => {
  const req = event.request;
  if (req.method !== 'GET') return;

  const url = new URL(req.url);
  /* خطوط Google: تُحفظ بعد أول تحميل فيبقى الخط نفسه بلا إنترنت */
  if (url.hostname === 'fonts.googleapis.com' || url.hostname === 'fonts.gstatic.com') {
    event.respondWith((async () => {
      const cache = await caches.open(FONTS);
      const hit = await cache.match(req, { ignoreVary: true });
      if (hit) return hit;
      try { const net = await fetch(req); if (net && (net.ok || net.type === 'opaque')) cache.put(req, net.clone()); return net; }
      catch (e) { return hit || Response.error(); }
    })());
    return;
  }
  if (url.origin !== self.location.origin) return;

  // لا تخزّن نقاط النهاية الديناميكية لـ API أو Netlify Functions
  if (url.pathname.startsWith('/api/') || url.pathname.startsWith('/.netlify/')) return;
  // المقاطع المسجّلة: لها ذاكرتها الخاصة وطلبات جزئية (Range) — لا يتدخّل عامل الخدمة
  if (url.pathname.startsWith('/audio/clips/') || req.headers.has('range')) return;

  // الصفحة الرئيسية وملفات الكود والبيانات: الشبكة أولًا مع تحديث الذاكرة والتراجع إليها عند انقطاع الاتصال
  if (req.mode === 'navigate' || url.pathname.startsWith('/data/') || /\.(?:html?|js|css|json|webmanifest)$/i.test(url.pathname)) {
    event.respondWith((async () => {
      try {
        const net = await fetch(req, { cache: 'no-cache' });
        if (net && net.ok) {
          const cache = await caches.open(CACHE);
          cache.put(req.mode === 'navigate' ? req : url.pathname, net.clone());
        }
        return net;
      } catch {
        const cache = await caches.open(CACHE);
        const hit = await cache.match(req, { ignoreSearch: true });
        return hit || (req.mode === 'navigate' ? cache.match('./index.html') : undefined);
      }
    })());
    return;
  }

  // الصور والملفات الصوتية والخطوط: الذاكرة أولًا مع تحديث خلفي
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    const cached = await cache.match(req, { ignoreSearch: true });
    const updating = fetch(req).then(net => {
      if (net && net.ok) cache.put(url.pathname, net.clone());
      return net;
    }).catch(() => cached);
    return cached || updating;
  })());
});
