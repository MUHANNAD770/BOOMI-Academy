Q = []
def q(unit, prompt, options, correct, explanation, labels=None, visual=None):
    item = {'id': f'pre_q{len(Q) + 1:03d}', 'unit_id': unit, 'type': 'choice', 'prompt': prompt,
            'options': options, 'correct_answer': correct, 'explanation': explanation}
    if labels: item['labels'] = {k: v for k, v in labels.items() if k in options}
    if visual: item['visual'] = visual
    assert correct in options, (prompt, correct, options)
    assert len(set(options)) == len(options), options
    Q.append(item)

def others(pool, keep, n):
    rest = [x for x in pool if x != keep]
    random.shuffle(rest)
    return rest[:n]

